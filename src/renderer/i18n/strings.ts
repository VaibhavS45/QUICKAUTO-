export const UI_LANGS: UiLang[] = ['en', 'es', 'fr', 'de', 'hi', 'pt', 'ja', 'zh']

function isUiLang(value: unknown): value is UiLang {
  return (
    value === 'en' ||
    value === 'es' ||
    value === 'fr' ||
    value === 'de' ||
    value === 'hi' ||
    value === 'pt' ||
    value === 'ja' ||
    value === 'zh'
  )
}

/** Translate a key, falling back to English, then to the key itself. Pure. */
export function translate(lang: unknown, key: UiKey): string {
  if (isUiLang(lang) && lang !== 'en') {
    const hit = translations[lang][key]
    if (typeof hit === 'string' && hit.length > 0) return hit
  }
  return en[key] ?? key
}

/**
 * Resolve a saved language preference to a concrete UI language. 'system'
 * (or anything unknown) maps from the OS/browser locale when it matches a
 * supported language, otherwise English. Pure and SSR-safe.
 */
export function resolveUiLanguage(preference: unknown): UiLang {
  if (isUiLang(preference) && preference !== 'en') return preference
  if (preference === 'en') return 'en'
  const tag =
    typeof navigator !== 'undefined' && typeof navigator.language === 'string'
      ? navigator.language.toLowerCase()
      : ''
  const prefix = tag.split('-')[0] ?? ''
  // Portuguese variants (pt-BR, pt-PT) share the same strings.
  if (prefix === 'pt' || tag.startsWith('pt')) return 'pt'
  if (isUiLang(prefix) && prefix !== 'en') return prefix
  return 'en'
}

/** All English keys (used by unit tests to assert translation coverage). */
export function uiKeys(): UiKey[] {
  return Object.keys(en) as UiKey[]
}
